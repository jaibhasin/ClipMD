import { chmodSync, copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { root, goEnv, runGo } from "./go.mjs";

const destination = join(root, "wasm");
function copyAsset(source, target) {
  // Go's module cache uses read-only files. Generated assets must be rebuildable.
  if (existsSync(target)) chmodSync(target, 0o644);
  copyFileSync(source, target);
  chmodSync(target, 0o644);
}
mkdirSync(destination, { recursive: true });
runGo(["build", "-trimpath", "-ldflags=-s -w", "-o", join(destination, "converter.wasm"), "./cmd/wasm"], {
  env: { ...goEnv, GOOS: "js", GOARCH: "wasm" },
});
chmodSync(join(destination, "converter.wasm"), 0o644);

const goroot = runGo(["env", "GOROOT"], { stdio: "pipe", encoding: "utf8" }).trim();
copyAsset(join(goroot, "lib/wasm/wasm_exec.js"), join(destination, "wasm_exec.js"));

// Include the licenses of the Go runtime and packages bundled in the module.
const licenses = join(root, "THIRD_PARTY_LICENSES");
mkdirSync(licenses, { recursive: true });
const goLicense = [join(goroot, "LICENSE"), join(goroot, "../LICENSE")].find(existsSync);
if (!goLicense) throw new Error("Could not find the Go runtime license");
copyAsset(goLicense, join(licenses, "Go.txt"));
const modules = [...new Set(runGo(["list", "-deps", "-f", "{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}", "./cmd/wasm"], {
  env: { ...goEnv, GOOS: "js", GOARCH: "wasm" },
  stdio: "pipe", encoding: "utf8",
}).trim().split("\n").filter(Boolean))];
for (const entry of modules) {
  const [name, , directory] = entry.split("\t");
  const filename = readdirSync(directory).find(file => /^licen[cs]e(?:\.|$)/i.test(file));
  if (!filename) throw new Error(`Missing license for ${name}`);
  copyAsset(join(directory, filename), join(licenses, `${name.replaceAll("/", "_")}.txt`));
}
writeFileSync(join(destination, "build.json"), JSON.stringify({
  generated: "Generated by npm run build. Do not edit manually.",
  go: runGo(["version"], { stdio: "pipe", encoding: "utf8" }).trim(),
  modules: modules.map(entry => {
    const [name, version] = entry.split("\t");
    return { name, version };
  }),
}, null, 2) + "\n");
console.log("Built the local Firecrawl WebAssembly converter and copied third-party licenses.");
